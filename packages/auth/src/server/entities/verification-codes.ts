/**
 * @spfn/auth - Verification Codes Entity
 *
 * Stores verification codes for email and phone verification
 * Codes expire after a configurable time period
 */

import { VERIFICATION_PURPOSES, VERIFICATION_TARGET_TYPES } from '../routes/schema';
import { text, index, integer, check } from 'drizzle-orm/pg-core';
import { id, timestamps, enumText, utcTimestamp } from '@spfn/core/db';
import { sql } from 'drizzle-orm';
import { authSchema } from './schema';

export const verificationCodes = authSchema.table('verification_codes',
    {
        id: id(),

        // Target (email or phone)
        // Email address or E.164 phone number (+821012345678)
        target: text('target').notNull(),
        targetType: enumText('target_type', VERIFICATION_TARGET_TYPES).notNull(),

        // Verification code
        // Default: 6-digit numeric code (configurable)
        // Generated by: crypto.randomInt(100000, 999999)
        code: text('code').notNull(),

        // Purpose of verification
        // Used to: prevent code reuse across different flows
        purpose: enumText('purpose', VERIFICATION_PURPOSES).notNull(),

        // Expiration timestamp
        // Default: 15 minutes from creation
        // Background job should clean up expired codes
        expiresAt: utcTimestamp('expires_at').notNull(),

        // Usage tracking
        // Timestamp when code was successfully used
        // null = not yet used, timestamp = used and no longer valid
        usedAt: utcTimestamp('used_at'),

        // Failed verification attempts counter
        // Incremented on each failed verification
        // Max attempts: 5 (enforced by check constraint)
        // Used for: rate limiting, security monitoring
        attempts: integer('attempts').notNull().default(0),

        ...timestamps(),
    },
    (table) => [
        // Database constraints
        // Limit verification attempts to prevent brute force attacks
        check('attempts_limit_check', sql`${table.attempts} >= 0 AND ${table.attempts} <= 10`),

        // Index for quick lookup by target and purpose
        index('target_purpose_idx')
            .on(table.target, table.purpose, table.expiresAt),
    ],
);

// Type exports
export type VerificationCode = typeof verificationCodes.$inferSelect;
export type NewVerificationCode = typeof verificationCodes.$inferInsert;
